export interface LingerPose {
  /** 眼球视线偏移 */
  gazeX: number;
  gazeY: number;
  irisScale: number;
  /** 单层上眼睑闭合度：-0.14（瞪大）~ 0（自然）~ 1.0（完全闭合） */
  upperLid: number;
  /** 上眼睑倾斜度（正=生气压眉，负=委屈八字） */
  upperLidTilt: number;
  /** 闭眼/眯眼风格："arc-up"（开心弯月 ⌒）或 "arc-down"（柔和/困倦 ◡） */
  closedEyeStyle: "arc-up" | "arc-down";
  /** 下眼睑柔化抬起度（0..0.55，配合开心/害羞柔和眯眼） */
  lowerLid: number;
  /** 左右眉位置与倾角 */
  browLY: number;
  browLTilt: number;
  browRY: number;
  browRTilt: number;
  mouth: LingerMouthShape;
  blush: number;
  tear: number;

  // === 全身骨骼姿态 ===
  /** 头部相对躯干的独立歪头角（度）与点低偏移（px） */
  headTiltDeg: number;
  headY: number;
  /** 躯干整体倾斜、上下位移与呼吸缩放 */
  torsoTiltDeg: number;
  bodyY: number;
  bodyScaleX: number;
  bodyScaleY: number;
  /** 左/右手臂相对肩关节的旋转角（度；左臂正值=向上抬，右臂负值=向上抬） */
  armLDeg: number;
  armRDeg: number;
  /** 左/右腿相对髋关节的旋转角（度） */
  legLDeg: number;
  legRDeg: number;
  /** 头顶呆毛倾角（度，作为情绪天线） */
  ahogeDeg: number;

  /** 特色符号 / 场景道具 */
  symbol: LingerSymbolType;
  /** 周期微动模式 */
  motion:
    | "breathe"
    | "bounce"
    | "excited"
    | "laugh"
    | "shiver"
    | "sway"
    | "sleep-pillow"
    | "talk"
    | "curious-lean"
    | "bored-play"
    | "none";
}

